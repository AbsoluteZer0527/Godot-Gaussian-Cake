"""Regenerate owned test geometry and both clips with the Gaussian Cake CLI.

Usage: python tools/generate_assets.py --cli ../Gaussian-Cake/build/Release/gc_cli.exe
The CLI is needed only for regeneration, never for running the addon.
"""
import argparse
import math
from pathlib import Path
import subprocess

parser = argparse.ArgumentParser()
parser.add_argument('--cli', required=True, type=Path)
args = parser.parse_args()
cli = args.cli.resolve()
root = Path(__file__).resolve().parents[1]
assets = root / 'examples' / 'assets'
assets.mkdir(parents=True, exist_ok=True)

def write_shape(path, stretch):
    slices, rings = 16, 8
    vertices = [(0.0, 1.0, 0.0)]
    for row in range(1, rings):
        phi = math.pi * row / rings
        for col in range(slices):
            theta = 2 * math.pi * col / slices
            vertices.append((math.sin(phi)*math.cos(theta)*stretch,
                             math.cos(phi), math.sin(phi)*math.sin(theta)*stretch))
    vertices.append((0.0, -1.0, 0.0))
    faces = []
    for col in range(slices):
        nxt = (col + 1) % slices
        faces.append((0, 1+nxt, 1+col))
        for row in range(rings - 2):
            a, b = 1+row*slices+col, 1+row*slices+nxt
            c, d = a+slices, b+slices
            faces += [(a, b, c), (b, d, c)]
        faces.append((len(vertices)-1, 1+(rings-2)*slices+col, 1+(rings-2)*slices+nxt))
    with path.open('w', encoding='utf-8') as out:
        out.write('# Procedural fixture generated by tools/generate_assets.py\n')
        for x, y, z in vertices:
            out.write(f'v {x:.8f} {y:.8f} {z:.8f} {0.18+0.12*(y+1):.6f} {0.55+0.18*(y+1):.6f} 0.35\n')
        for a, b, c in faces:
            out.write(f'f {a+1} {b+1} {c+1}\n')

write_shape(assets / 'round.obj', 1.0)
write_shape(assets / 'tall.obj', 0.48)
for mode, suffix in [('topology', 'glb'), ('splats', 'gcsplat')]:
    project = assets / f'{mode}.gcproject'
    subprocess.run([str(cli), 'new', '--mode', mode, '--a', str(assets/'round.obj'),
                    '--b', str(assets/'tall.obj'), '--output', str(project), '--duration', '1',
                    '--style', 'classic', '--rigid', '0', '--count', '4096', '--samples', '1000',
                    '--mixtures', '4'], check=True, cwd=root)
    subprocess.run([str(cli), 'export', str(project), '--output', str(assets/f'round_to_tall.{suffix}'),
                    '--fps', '24'], check=True, cwd=root)

